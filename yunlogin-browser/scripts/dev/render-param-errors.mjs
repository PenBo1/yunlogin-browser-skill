#!/usr/bin/env node
/**
 * Render the request-parameter errors the sweep collected.
 *
 * The availability sweep sends one generic body per route. When a route needs real identifiers it
 * answers with a validation code and often names the missing field, which is direct evidence about
 * the request contract. This renders that evidence; it makes no network calls.
 *
 * Usage: node scripts/dev/render-param-errors.mjs
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..", "references", "server-api");
const sweep = JSON.parse(await readFile(path.join(dir, "route-sweep.json"), "utf8"));

// Codes the sweep uses when the generic body was rejected rather than accepted.
const PARAM_CODES = new Set([7, 400, 401, 4009, 4020, 50004, 10003, 10006, 10012, 10017, 10019, 10022]);
// Keep genuine contract evidence; drop plain lookup failures like `NOT_FOUND` or `record not found`.
const CONTRACT = /required|Key:|\u7f3a\u5c11|\u53c2\u6570|unknown field|\u4e0d\u80fd\u4e3a\u7a7a|validation|invalid|\u7c7b\u578b|\u4e0d\u5408\u6cd5|\u5b57\u6bb5|\u5fc5\u987b/i;
const LOOKUP = /NOT_FOUND|record not found|\u4e0d\u5b58\u5728|\u4e0d\u5c5e\u4e8e\u5f53\u524d\u56e2\u961f/i;
const rows = sweep.results.filter((r) => r.status === "live" && PARAM_CODES.has(Number(r.code)) && r.msg && CONTRACT.test(String(r.msg)) && !LOOKUP.test(String(r.msg)));
const named = rows.filter((r) => !/^(\u8bf7\u6c42\u53c2\u6570\u9519\u8bef|\u53c2\u6570\u9519\u8bef|\u83b7\u53d6\u5931\u8d25)$/.test(String(r.msg).trim()));

const lines = [];
lines.push("# Request Parameter Errors");
lines.push("");
lines.push("Each route below was called once with a generic body and answered with a validation code, so the");
lines.push("message is direct evidence about the request contract. Generated by");
lines.push("`node scripts/dev/render-param-errors.mjs` from `route-sweep.json`; no request was re-sent.");
lines.push("");
lines.push(`- Routes that rejected the generic body: **${rows.length}**`);
lines.push(`- Of those, messages that name a field or a type: **${named.length}**`);
lines.push("");
lines.push("## Messages That Name A Field Or Type");
lines.push("");
lines.push("| Method | Path | Code | Message |");
lines.push("| --- | --- | ---: | --- |");
for (const r of named.sort((a, b) => a.path.localeCompare(b.path))) {
  const msg = String(r.msg).replace(/\s+/g, " ").replace(/\|/g, "\\|").slice(0, 160);
  lines.push(`| \`${r.method}\` | \`${r.path}\` | \`${r.code}\` | ${msg} |`);
}
lines.push("");
lines.push("## Generic Rejections");
lines.push("");
lines.push("These answered with a bare parameter error, so the required fields still have to come from the");
lines.push("client call site or a targeted probe.");
lines.push("");
lines.push("| Method | Path | Code | Message |");
lines.push("| --- | --- | ---: | --- |");
for (const r of rows.filter((x) => !named.includes(x)).sort((a, b) => a.path.localeCompare(b.path))) {
  const msg = String(r.msg).replace(/\s+/g, " ").replace(/\|/g, "\\|").slice(0, 80);
  lines.push(`| \`${r.method}\` | \`${r.path}\` | \`${r.code}\` | ${msg} |`);
}
lines.push("");

await writeFile(path.join(dir, "PARAM_ERRORS.md"), lines.join("\n"), "utf8");
console.log(`Wrote PARAM_ERRORS.md: ${rows.length} rejected routes (${named.length} name a field)`);
