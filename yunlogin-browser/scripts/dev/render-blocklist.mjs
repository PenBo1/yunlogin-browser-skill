#!/usr/bin/env node
/**
 * Render the withheld-route registry: every route the sweep refuses to probe, with the reason and the
 * request keys the client sends. Reads route-sweep.json and client-params.json; no network access.
 *
 * Usage: node scripts/dev/render-blocklist.mjs
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..", "references", "server-api");
const sweep = JSON.parse(await readFile(path.join(dir, "route-sweep.json"), "utf8"));
const params = JSON.parse(await readFile(path.join(dir, "client-params.json"), "utf8"));

const keysByRoute = {};
for (const info of Object.values(params.params)) {
  if (!info.route) continue;
  keysByRoute[info.route] = [...new Set([...(keysByRoute[info.route] ?? []), ...(info.keys ?? [])])];
}

// A single ordered rule list keeps the reason text stable and auditable.
const RULES = [
  [/(changePwd|modifyMobileEmail|bindPhoneEmail|ubindAuth|setInfo|forgetPwd|bind\b)/i, "Identity or credentials"],
  [/(sendCode|sendSms|sendsms|getCode|sendemailcode|emailyanzhen)/i, "Sends an SMS or email code"],
  [/(register|company\/create|company\/change)/i, "Creates an account or company"],
  [/(Authentication|authentication)/i, "Real-name authentication"],
  [/(paypal|repayrecharge|pay_scan|balance_pay|scanrecharge)/i, "Spends money"],
  [/(logout)/i, "Ends the session"],
  [/(uninstall|deletePluginCrx|deletePluginGroup|rpa\/deleteRpa|rpa\/destroyRpaCarbonConfig|deleteRpaGroupByGroupIds|deleteRpaPlanManagement|deleteRpaCarbonConfig|deletePromotionLink|customplatformedit|roleRemove)/i, "Bulk destructive delete"],
  [/(dept\/create|role-group\/create|createPluginGroup|generateuuid|migrate\/apply)/i, "Writes a row for an empty or generated body"],
  [/(member\/change|role\/del|cookie\/clear|user\/delete|putdeleteshop|batchDel|batchdelete)/i, "Deletes or rewrites shared data"],
];
function reasonFor(row) {
  const hay = `${row.name ?? ""} ${row.path}`;
  for (const [re, label] of RULES) if (re.test(hay)) return label;
  return "Withheld by the classifier";
}

// Families proved safe by an explicit create-verify-delete round trip (see WRITE_ROUNDTRIPS.md).
const ROUND_TRIPPED = new Set([
  "POST /v2/rpa/createRpaGroup",
  "DELETE /v2/rpa/deleteRpaGroup",
  "POST /v2/team/dept/create",
  "POST /v2/team/dept/del",
  "POST /v2/retail/createPromotionLink",
  "DELETE /v2/retail/deletePromotionLink",
  "POST /v2/team/role-group/create",
  "POST /v2/team/role-group/del",
]);
const rows = sweep.results.filter((r) => r.status === "skipped");
rows.sort((a, b) => a.path.localeCompare(b.path));

const lines = [];
lines.push("# Withheld Routes");
lines.push("");
lines.push("Every route the live sweep refuses to probe, with the reason it is withheld and the candidate request keys");
lines.push("parsed from the client call site. Keys are heuristic: a call site that passes a variable yields none,");
lines.push("and a large argument expression can add noise. Confirm against [CLIENT_CALLSITES.md](CLIENT_CALLSITES.md).");
lines.push("");
lines.push(`- Withheld routes: **${rows.length}** of ${sweep.total}`);
lines.push(`- Reason: ${sweep.results.filter((r) => r.status === "skipped").every((r) => r.reason === "catastrophic blocklist") ? "all are on the catastrophic blocklist" : "mixed"}`);
lines.push("");
lines.push("Generated by `node scripts/dev/render-blocklist.mjs` from `route-sweep.json` and `client-params.json`.");
lines.push("");
lines.push("| Method | Path | Client name | Why withheld | Candidate request keys | Round-trip verified |");
lines.push("| --- | --- | --- | --- | --- | --- |");
for (const r of rows) {
  const keys = keysByRoute[`${r.method} ${r.path}`] ?? [];
  const rt = ROUND_TRIPPED.has(`${r.method} ${r.path}`) ? "yes" : "no";
  lines.push(`| \`${r.method}\` | \`${r.path}\` | ${r.name ? `\`${r.name}\`` : "-"} | ${reasonFor(r)} | ${keys.length ? keys.map((k) => `\`${k}\``).join(", ") : "_not parsed from the client_"} | ${rt} |`);
}
lines.push("");
lines.push("Routes marked `_not parsed from the client_` still have a documented reason; their request body is built");
lines.push("from a variable at the call site, so the keys must come from the endpoint document or a live probe.");
lines.push("");

await writeFile(path.join(dir, "BLOCKLIST.md"), lines.join("\n"), "utf8");
console.log(`Wrote BLOCKLIST.md: ${rows.length} withheld routes`);
